/**
 * Generate daily fortune for a specific date
 * @param {number} year 
 * @param {number} month (0-based)
 * @param {number} day 
 * @returns {Object} fortune object
 */
function generateDailyFortune(year, month, day) {
    // Create multiple seeds for different aspects
    const baseSeed = createComplexSeed(year, month, day);
    
    // Generate independent scores for each category
    const overallScore = generateScore(baseSeed, 1);
    const moneyScore = generateScore(baseSeed, 2);
    const loveScore = generateScore(baseSeed, 3);
    const healthScore = generateScore(baseSeed, 4);
    
    // Get day of week for context
    const date = new Date(year, month, day);
    const dayOfWeek = date.getDay();
    const dayNames = ['일요일', '월요일', '화요일', '수요일', '목요일', '금요일', '토요일'];
    
    // Calculate additional fortune elements
    const element = getElement(baseSeed);
    const stem = getStem(baseSeed);
    const branch = getBranch(baseSeed);
    
    // Generate fortune data
    const fortune = {
        year,
        month,
        day,
        seed: baseSeed,
        dayOfWeek: dayNames[dayOfWeek],
        score: overallScore,
        scoreStars: getStarRating(overallScore),
        overview: generateOverview(baseSeed, overallScore, dayNames[dayOfWeek], element, stem, branch),
        money: generateMoneyFortune(baseSeed, moneyScore),
        love: generateLoveFortune(baseSeed, loveScore),
        health: generateHealthFortune(baseSeed, healthScore),
        luckyNumber: generateLuckyNumber(baseSeed),
        luckyColor: generateLuckyColor(baseSeed).name,
        luckyColorCode: generateLuckyColor(baseSeed).code,
        luckyDirection: generateLuckyDirection(baseSeed)
    };
    
    return fortune;
}

/**
 * Create complex seed from date for maximum variation
 */
function createComplexSeed(year, month, day) {
    const date = new Date(year, month, day);
    const dayOfYear = Math.floor((date - new Date(year, 0, 0)) / 86400000);
    const weekOfYear = Math.floor(dayOfYear / 7);
    
    // Use prime numbers and modular arithmetic for better distribution
    const seed = (
        (year * 983) + 
        (month * 509) + 
        (day * 251) + 
        (dayOfYear * 127) + 
        (weekOfYear * 61)
    ) % 2147483647; // Large prime number
    
    return seed;
}

/**
 * Advanced seeded random number generator
 * Uses Xorshift algorithm for better randomness
 */
function seededRandom(seed) {
    let state = seed || 1;
    
    return function() {
        // Xorshift algorithm
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        
        // Ensure positive value
        const value = (state < 0 ? ~state + 1 : state) % 2147483647;
        return value / 2147483647;
    };
}

/**
 * Generate score (1-5) with proper distribution
 */
function generateScore(seed, offset) {
    const random = seededRandom(seed + offset * 10000);
    const value = random();
    
    // Distribution: 1=10%, 2=20%, 3=35%, 4=25%, 5=10%
    if (value < 0.10) return 1;
    if (value < 0.30) return 2;
    if (value < 0.65) return 3;
    if (value < 0.90) return 4;
    return 5;
}

/**
 * Convert score to star rating
 */
function getStarRating(score) {
    const fullStars = '★'.repeat(score);
    const emptyStars = '☆'.repeat(5 - score);
    return fullStars + emptyStars;
}

/**
 * Get Five Element (오행)
 */
function getElement(seed) {
    const random = seededRandom(seed + 1);
    const elements = ['목(木)', '화(火)', '토(土)', '금(金)', '수(水)'];
    return elements[Math.floor(random() * elements.length)];
}

/**
 * Get Heavenly Stem (천간)
 */
function getStem(seed) {
    const random = seededRandom(seed + 2);
    const stems = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
    return stems[Math.floor(random() * stems.length)];
}

/**
 * Get Earthly Branch (지지)
 */
function getBranch(seed) {
    const random = seededRandom(seed + 3);
    const branches = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];
    return branches[Math.floor(random() * branches.length)];
}

